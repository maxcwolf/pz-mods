local S = CSG_Selection

test("container stacks merge and remove", function()
    local sel = S.new()
    local key = S.containerKey("Base.Bag_ALICEpack", 1)
    eq(key, "Base.Bag_ALICEpack#1")
    S.addToContainer(sel, key, "Base.Pop", 1)
    S.addToContainer(sel, key, "Base.Pop", 2)
    S.addToContainer(sel, key, "Base.Axe")
    eq(#S.containerItems(sel, key), 2)
    eq(S.containerItems(sel, key)[1].count, 3)
    S.removeFromContainer(sel, key, "Base.Pop", 3)
    eq(S.containerItems(sel, key)[1].fullType, "Base.Axe")
    S.removeFromContainer(sel, key, "Base.Axe")
    eq(sel.containers[key], nil)
end)

test("containerWeight multiplies counts", function()
    local sel = S.new()
    S.addToContainer(sel, "k", "Base.Pop", 3)
    S.addToContainer(sel, "k", "Base.Axe", 1)
    local weights = { ["Base.Pop"] = 0.5, ["Base.Axe"] = 3 }
    eq(S.containerWeight(sel, "k", function(t) return weights[t] end), 4.5)
end)

test("isEmpty", function()
    local sel = S.new()
    eq(S.isEmpty(sel), true)
    S.setHand(sel, "primary", "Base.Axe")
    eq(S.isEmpty(sel), false)
    S.setHand(sel, "primary", nil)
    S.addToContainer(sel, "k", "Base.Pop")
    eq(S.isEmpty(sel), false)
end)

test("serialize round trip is stable", function()
    local sel = S.new()
    S.setHand(sel, "primary", "Base.Axe")
    S.setAttachment(sel, "SmallBeltLeft", "Base.Wrench")
    S.setAttachment(sel, "Back", "Base.Crowbar")
    S.addToContainer(sel, "Base.Bag_ALICEpack#1", "Base.Pop", 2)
    S.addToContainer(sel, "Base.Bag_ALICEpack#1", "Base.Axe", 1)
    local text = S.serialize(sel)
    local back = S.deserialize(text)
    eq(S.serialize(back), text)
    eq(back.hands.primary, "Base.Axe")
    eq(back.attachments.Back, "Base.Crowbar")
    eq(S.containerItems(back, "Base.Bag_ALICEpack#1")[1].count, 2)
end)

test("deserialize ignores junk", function()
    local sel = S.deserialize("garbage\nhand\t\t\ncontainer\tk\tBase.Pop\tzero\nattach\tBack\tBase.Crowbar\n\n")
    eq(sel.attachments.Back, "Base.Crowbar")
    eq(S.containerItems(sel, "k")[1].count, 1)
    eq(sel.hands[""], nil)
end)

test("pruneUnknown drops unknown types everywhere", function()
    local sel = S.deserialize("hand\tprimary\tGone.Axe\nattach\tBack\tBase.Crowbar\ncontainer\tk\tGone.Pop\t1\ncontainer\tk\tBase.Pop\t1")
    S.pruneUnknown(sel, function(t) return t:sub(1, 5) == "Base." end)
    eq(sel.hands.primary, nil)
    eq(sel.attachments.Back, "Base.Crowbar")
    eq(#S.containerItems(sel, "k"), 1)
    eq(S.containerItems(sel, "k")[1].fullType, "Base.Pop")
end)

test("the loaded-ammo option defaults on, round trips and is not gear", function()
    local sel = S.new()
    eq(sel.options.loaded, true, "default")
    eq(S.isEmpty(sel), true, "options alone are not a selection")
    S.setOption(sel, "loaded", false)
    eq(S.serialize(sel), "option\tloaded\t0")
    local back = S.deserialize(S.serialize(sel))
    eq(back.options.loaded, false)
    eq(S.deserialize("").options.loaded, true, "missing option keeps the default")
    eq(S.deserialize("option\tloaded\t1").options.loaded, true)
    eq(S.deserialize("option\tbogus\t1").options.bogus, nil, "unknown options are dropped")
end)
