local Tether = require("HorseShootAndHitch/tether")

test("low and tall hoppable fences are tie points", function()
    eq(Tether.isTiePoint({ hoppable = true }), true)
    eq(Tether.isTiePoint({ tallHoppable = true }), true)
end)

test("trees and vanilla hitching objects are tie points", function()
    eq(Tether.isTiePoint({ tree = true }), true)
    eq(Tether.isTiePoint({ canAttachAnimal = true }), true)
end)

test("lamp posts, sign poles, railings and fence posts are tie points by sprite", function()
    eq(Tether.isTiePoint({ spriteName = "lighting_outdoor_01_1" }), true)
    eq(Tether.isTiePoint({ spriteName = "street_roadsigns_01_11" }), true)
    eq(Tether.isTiePoint({ spriteName = "fixtures_railings_01_33" }), true)
    eq(Tether.isTiePoint({ spriteName = "fencing_01_59" }), true)
    eq(Tether.isTiePoint({ spriteName = "electricity_pylon_11" }), true)
end)

test("walls, furniture and nothing at all are not tie points", function()
    eq(Tether.isTiePoint({ spriteName = "walls_exterior_house_01_0" }), false)
    eq(Tether.isTiePoint({ spriteName = "furniture_seating_indoor_01_0" }), false)
    eq(Tether.isTiePoint({}), false)
    eq(Tether.isTiePoint(nil), false)
end)

test("a sprite prefix must match from the start of the name", function()
    eq(Tether.isPoleSprite("my_fencing_01_0"), false)
    eq(Tether.isPoleSprite(nil), false)
end)

test("reins are used before a rope, and nothing means the horse cannot be tied", function()
    eq(Tether.tieCost(true, true), "reins")
    eq(Tether.tieCost(true, false), "reins")
    eq(Tether.tieCost(false, true), "rope")
    eq(Tether.tieCost(false, false), nil)
end)

test("records keep the post square, sprite and cost", function()
    local r = Tether.record(10, 20, 0, "fencing_01_3", "rope")
    eq(r.x, 10); eq(r.y, 20); eq(r.z, 0); eq(r.sprite, "fencing_01_3"); eq(r.cost, "rope")
    eq(Tether.isValidRecord(r), true)
end)

test("broken records are rejected", function()
    eq(Tether.isValidRecord(nil), false)
    eq(Tether.isValidRecord({ x = 1, y = 2 }), false)
    eq(Tether.isValidRecord("10,20"), false)
end)

test("distance is measured to the centre of the post tile", function()
    local r = Tether.record(10, 20, 0)
    near(Tether.distanceToPost(10.5, 20.5, r), 0)
    near(Tether.distanceToPost(13.5, 24.5, r), 5)
end)

test("a horse within the radius plus half a tile is in reach", function()
    local r = Tether.record(10, 20, 0)
    eq(Tether.isOutOfReach(12.5, 20.5, r, 2), false, "exactly two tiles")
    eq(Tether.isOutOfReach(13.0, 20.5, r, 2), false, "two and a half")
    eq(Tether.isOutOfReach(13.2, 20.5, r, 2), true, "past the edge")
end)

test("the default radius is two tiles", function()
    local r = Tether.record(0, 0, 0)
    eq(Tether.isOutOfReach(3.2, 0.5, r), true)
    eq(Tether.isOutOfReach(2.9, 0.5, r), false)
end)

test("only a horse far beyond the radius counts as lost", function()
    local r = Tether.record(0, 0, 0)
    eq(Tether.isLost(6.5, 0.5, r, 2), false)
    eq(Tether.isLost(11.0, 0.5, r, 2), true)
end)

test("the return tile is one step inside the radius on the horse's side", function()
    local r = Tether.record(10, 20, 0)
    local x, y = Tether.returnTile(16.5, 20.5, r, 2)
    eq(x, 11); eq(y, 20)
    x, y = Tether.returnTile(10.5, 14.5, r, 3)
    eq(x, 10); eq(y, 18)
end)

test("the return tile is never the post's own tile", function()
    local r = Tether.record(10, 20, 0)
    local x, y = Tether.returnTile(10.5, 20.5, r, 2)
    eq(x == 10 and y == 20, false)
end)
