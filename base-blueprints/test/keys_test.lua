local Keys = require("BaseBlueprints/keys")

test("keys: square and column keys round-trip, negatives included", function()
    local key = Keys.square(10612, 9402, -1)
    eq(key, "10612,9402,-1")
    local x, y, z = Keys.parse(key)
    eq(x, 10612)
    eq(y, 9402)
    eq(z, -1)
    eq(Keys.columnOf(key), "10612,9402")
    local cx, cy = Keys.parseColumn("5,-6")
    eq(cx, 5)
    eq(cy, -6)
    eq(Keys.parse("nope"), nil)
end)

test("keys: sorted orders by level, row, column", function()
    local list = Keys.sorted({ ["2,1,0"] = 1, ["1,1,1"] = 1, ["9,0,0"] = 1, ["1,1,0"] = 1 })
    eq(table.concat(list, " "), "9,0,0 1,1,0 2,1,0 1,1,1")
end)
