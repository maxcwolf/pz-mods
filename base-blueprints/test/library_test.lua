local Library = require("BaseBlueprints/library")
local Blueprint = require("BaseBlueprints/blueprint")

test("library: index round-trips and upsert puts newest first", function()
    local bp = Blueprint.new({ id = "home-1", name = "Home", area = { x1 = 0, y1 = 0, x2 = 10, y2 = 4, z1 = 0, z2 = 1 } }, {})
    local entries = {}
    Library.upsert(entries, Library.entryFor(bp, true))
    Library.upsert(entries, { id = "farm-2", name = "Farm" })
    eq(entries[1].id, "farm-2")
    eq(entries[2].x, 5)
    eq(entries[2].auto, true)
    Library.upsert(entries, { id = "home-1", name = "Home again" })
    eq(#entries, 2)
    eq(entries[1].name, "Home again")
    local back = Library.parseIndex(Library.indexLines(entries))
    eq(#back, 2)
    eq(back[2].id, "farm-2")
    eq(Library.idForName(back, "home AGAIN"), "home-1")
    Library.remove(back, "home-1")
    eq(#back, 1)
end)

test("library: unreadable index lines are skipped", function()
    local entries = Library.parseIndex({ Library.HEADER, "{id=\"a\",name=\"A\"}", "garbage", "{id=1}" })
    eq(#entries, 1)
    eq(#Library.parseIndex(nil), 0)
    eq(Library.fileFor("a-1"), "BaseBlueprints_a-1.txt")
end)
