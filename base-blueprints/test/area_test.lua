local Area = require("BaseBlueprints/area")

test("area: building plus margin reaches the roof level", function()
    local a = Area.fromBuilding({ x = 100, y = 200, w = 10, h = 8, minLevel = 0, maxLevel = 1 }, 1)
    eq(a.x1, 99)
    eq(a.y1, 199)
    eq(a.x2, 110, "east wall square included")
    eq(a.y2, 208)
    eq(a.z1, 0)
    eq(a.z2, 2, "roof level")
    eq(Area.count(a), 12 * 10 * 3)
    ok(Area.contains(a, 110, 208, 2))
    ok(not Area.contains(a, 111, 208, 2))
    ok(Area.isValid(a))
end)

test("area: margin is at least 1 and basements count", function()
    local a = Area.fromBuilding({ x = 0, y = 0, w = 2, h = 2, minLevel = -1, maxLevel = 0 }, 0)
    eq(a.x1, -1)
    eq(a.z1, -1)
    eq(#Area.keys(a), Area.count(a))
    eq(Area.keys(a)[1], "-1,-1,-1")
end)

test("area: invalid and huge areas are rejected", function()
    ok(not Area.isValid(nil))
    ok(not Area.isValid({ x1 = 0, y1 = 0, x2 = -1, y2 = 0, z1 = 0, z2 = 0 }))
    ok(not Area.isValid({ x1 = 0, y1 = 0, x2 = 999, y2 = 999, z1 = 0, z2 = 0 }))
end)
