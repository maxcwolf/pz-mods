local Pending = require("BaseBlueprints/pending")

test("pending: schedule groups squares by column and take empties it", function()
    local root = Pending.init({})
    local n = Pending.schedule(root, "a", "A", { ["1,1,0"] = {}, ["1,1,1"] = { { cls = "IsoObject", sprite = "x_1" } }, ["2,1,0"] = {} })
    eq(n, 3)
    eq(table.concat(Pending.columns(root), " "), "1,1 2,1")
    local entries = Pending.take(root, "1,1")
    eq(#entries, 2)
    eq(entries[2].z, 1)
    eq(Pending.take(root, "1,1"), nil)
    Pending.record(root, "a", { added = 1 })
    Pending.record(root, "a", { removed = 2 })
    eq(Pending.left(root, "a"), 1)
    eq(root.runs.a.added, 1)
    eq(root.runs.a.removed, 2)
end)

test("pending: scheduling again replaces, cancel removes only that blueprint", function()
    local root = Pending.init({})
    Pending.schedule(root, "a", "A", { ["1,1,0"] = {} })
    Pending.schedule(root, "b", "B", { ["1,1,0"] = {}, ["5,5,0"] = {} })
    Pending.schedule(root, "a", "A", { ["1,1,0"] = {} })
    eq(#root.columns["1,1"], 2)
    Pending.cancel(root, "b")
    eq(#root.columns["1,1"], 1)
    eq(root.columns["5,5"], nil)
    eq(root.runs.b, nil)
    eq(Pending.left(root, "missing"), 0)
end)
