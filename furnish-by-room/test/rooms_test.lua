--- Room detection from the game's room names, and picking the room to
--- open on.
local Rooms = require("FurnishByRoom/rooms")

test("rooms: home rooms map to the six types", function()
    eq(Rooms.fromGameName("kitchen"), "kitchen")
    eq(Rooms.fromGameName("bedroom"), "bedroom")
    eq(Rooms.fromGameName("livingroom"), "living")
    eq(Rooms.fromGameName("dining"), "dining")
    eq(Rooms.fromGameName("bar"), "bar")
    eq(Rooms.fromGameName("garagestorage"), "garage")
end)

test("rooms: variants and look-alikes", function()
    eq(Rooms.fromGameName("ww_bar"), "bar")
    eq(Rooms.fromGameName("barkitchen"), "kitchen", "a bar's kitchen is a kitchen")
    eq(Rooms.fromGameName("kidsbedroom"), "bedroom")
    eq(Rooms.fromGameName("bandlivingroom"), "living")
    eq(Rooms.fromGameName("motelroom"), "bedroom")
    eq(Rooms.fromGameName("restaurantdining"), "dining")
    eq(Rooms.fromGameName("shed"), "garage")
    eq(Rooms.fromGameName("BEDROOM"), "bedroom", "case")
    eq(Rooms.fromGameName("kitchenwares"), nil, "a shop")
    eq(Rooms.fromGameName("barbershop"), nil, "not a bar")
    eq(Rooms.fromGameName("bathroom"), nil)
    eq(Rooms.fromGameName(""), nil)
    eq(Rooms.fromGameName(nil), nil)
end)

test("rooms: pick prefers detected, then last, then kitchen", function()
    eq(Rooms.pick("bar", "garage"), "bar")
    eq(Rooms.pick(nil, "garage"), "garage")
    eq(Rooms.pick("nonsense", nil), "kitchen")
    eq(#Rooms.ORDER, 6)
    ok(Rooms.isRoom("living"))
    ok(not Rooms.isRoom("bathroom"))
    eq(Rooms.labelKey("bar"), "UI_FBR_Room_bar")
end)
