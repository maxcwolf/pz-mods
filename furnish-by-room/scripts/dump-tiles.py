#!/usr/bin/env python3
"""Writes test/fixtures/vanilla-tiles.lua from the game's tile definitions,
so the catalog tests run against the real furniture list. The fixture is
game data, so it is gitignored; run this once per game update.

Usage: python3 -I scripts/dump-tiles.py [path/to/newtiledefinitions.tiles]
"""
import os
import struct
import sys

DEFAULT = os.path.expanduser(
    "~/Library/Application Support/Steam/steamapps/common/ProjectZomboid/"
    "Project Zomboid.app/Contents/Java/media/newtiledefinitions.tiles")


def read_tiles(path):
    """Parses the binary tdef file into {sheet: [props dict per tile]}."""
    data = open(path, "rb").read()
    pos = 4
    assert data[:4] == b"tdef", "not a tile definition file"

    def i32():
        nonlocal pos
        value = struct.unpack_from("<i", data, pos)[0]
        pos += 4
        return value

    def line():
        nonlocal pos
        end = data.index(b"\n", pos)
        text = data[pos:end].decode("latin-1")
        pos = end + 1
        return text

    i32()
    sheets = {}
    for _ in range(i32()):
        name = line()
        line()
        i32(); i32(); i32()
        tiles = []
        for _ in range(i32()):
            props = {}
            for _ in range(i32()):
                key = line()
                props[key] = line()
            tiles.append(props)
        sheets[name] = tiles
    return sheets


def lua_string(text):
    """Quotes text as a Lua string literal."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    """Dumps moveable and floor tiles as Lua records."""
    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_path = os.path.join(root, "test", "fixtures", "vanilla-tiles.lua")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    rows = []
    for sheet, tiles in sorted(read_tiles(path).items()):
        for index, props in enumerate(tiles):
            moveable = "IsMoveAble" in props
            floor = "solidfloor" in props
            if not (moveable or floor):
                continue
            fields = ["sheet=" + lua_string(sheet), "index=%d" % index,
                      "sprite=" + lua_string("%s_%d" % (sheet, index))]
            for key, name in (("GroupName", "group"), ("CustomName", "custom"),
                              ("container", "container"), ("Facing", "facing")):
                if key in props:
                    fields.append(name + "=" + lua_string(props[key]))
            if moveable:
                fields.append("moveable=true")
            if floor:
                fields.append("floor=true")
            if "SpriteGridPos" in props and props["SpriteGridPos"] != "0,0":
                fields.append("anchor=false")
            rows.append("{" + ",".join(fields) + "}")
    with open(out_path, "w") as handle:
        handle.write("-- Generated by scripts/dump-tiles.py from the game's tile definitions.\n")
        handle.write("return {\n" + ",\n".join(rows) + "\n}\n")
    print("wrote %d tiles to %s" % (len(rows), out_path))


if __name__ == "__main__":
    main()
