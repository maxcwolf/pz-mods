--- End-to-end tests of the game adapter against the fake game, which copies
--- the engine's own capacity rules (see test/harness/fake-game.lua).
local Fake = require("fake-game")
local Settings = require("VehicleStorageCapacity/settings")
local Vehicles = require("VehicleStorageCapacity/vehicles")

--- Builds settings from sandbox-style percents.
local function settings(trunk, seat, glovebox, trailer)
    return Settings.fromSandbox({ TrunkPercent = trunk, SeatPercent = seat, GloveBoxPercent = glovebox, TrailerPercent = trailer })
end

--- Builds a vanilla-style car: item-backed trunk, glove box, two seats and a gas tank.
local function vanillaCar(trunkCondition)
    local trunk = Fake.part({ id = "TruckBed", itemTypes = { "Base.NormalTrunk" }, conditionAffects = true })
    local glove = Fake.part({ id = "GloveBox", scriptCapacity = 5 })
    local seat0 = Fake.part({ id = "SeatFrontLeft", seat = 0, scriptCapacity = 20 })
    local seat1 = Fake.part({ id = "SeatFrontRight", seat = 1, scriptCapacity = 20 })
    local tank = Fake.part({ id = "GasTank", contentType = "Gasoline", itemTypes = { "Base.NormalGasTank" } })
    local car = Fake.vehicle("Base.CarNormal", { trunk, glove, seat0, seat1, tank })
    Fake.spawnItem(trunk, "Base.NormalTrunk", 50, trunkCondition or 100)
    return car, trunk, glove, seat0, seat1, tank
end

Vehicles.resetCaches()

test("vehicles: vanilla car gets each category's percent; fuel tank untouched", function()
    local car, trunk, glove, seat0, _, tank = vanillaCar()
    local changed = Vehicles.applyVehicle(car, settings(200, 150, 300, 100))
    eq(changed, 4, "changed parts")
    eq(trunk:getContainerCapacity(), 100, "trunk")
    eq(glove:getContainerCapacity(), 15, "glove box")
    eq(seat0:getContainerCapacity(), 30, "seat")
    eq(tank.setCalls, 0, "gas tank")
end)

test("vehicles: applying twice changes nothing the second time", function()
    local car, trunk = vanillaCar()
    local s = settings(200, 150, 300, 100)
    Vehicles.applyVehicle(car, s)
    local calls = trunk.setCalls
    eq(Vehicles.applyVehicle(car, s), 0, "second pass")
    eq(trunk.setCalls, calls, "no extra writes")
    eq(trunk:getContainerCapacity(), 100, "still doubled, not quadrupled")
end)

test("vehicles: a damaged trunk keeps the game's condition penalty, then scales", function()
    local car, trunk = vanillaCar(50)
    eq(trunk:getContainerCapacity(), 30, "game value at 50 condition")
    Vehicles.applyVehicle(car, settings(200, 100, 100, 100))
    eq(trunk:getContainerCapacity(), 60, "doubled")
end)

test("vehicles: removing and reinstalling a trunk does not compound", function()
    local car, trunk = vanillaCar()
    local s = settings(200, 100, 100, 100)
    Vehicles.applyVehicle(car, s)
    local item = trunk:getInventoryItem()
    trunk:setInventoryItem(nil)
    Vehicles.applyVehicle(car, s)
    eq(trunk:getContainerCapacity(), 0, "no trunk, no storage")
    eq(trunk:getModData()[Vehicles.KEY_BASE], nil, "record forgotten")
    trunk:setInventoryItem(item)
    Vehicles.applyVehicle(car, s)
    eq(trunk:getContainerCapacity(), 100, "doubled once")
end)

test("vehicles: a bigger trunk landing on the applied value still scales", function()
    local car, trunk = vanillaCar()
    local s = settings(200, 100, 100, 100)
    Vehicles.applyVehicle(car, s)
    trunk:setInventoryItem(Fake.item("Base.BigTrunk", 100, 100))
    eq(trunk:getContainerCapacity(), 100, "game value equals the old applied value")
    Vehicles.applyVehicle(car, s)
    eq(trunk:getContainerCapacity(), 200, "new item detected")
end)

test("vehicles: KI5 trunk with script capacity scales once, even across respawned items", function()
    local trunk = Fake.part({ id = "W460Trunk", itemTypes = { "damnCraft.Trunk" }, scriptCapacity = 120 })
    local truck = Fake.vehicle("Base.84mercW460", { trunk })
    local s = settings(200, 100, 100, 100)
    Vehicles.applyVehicle(truck, s)
    eq(trunk:getContainerCapacity(), 120, "empty slot left alone")
    Fake.spawnItem(trunk, "damnCraft.Trunk", 35)
    eq(trunk:getInventoryItem():getMaxCapacity(), 120, "vanilla copied the unscaled value")
    Vehicles.applyVehicle(truck, s)
    eq(trunk:getContainerCapacity(), 240, "doubled")
    trunk:setInventoryItem(nil)
    Vehicles.applyVehicle(truck, s)
    Fake.spawnItem(trunk, "damnCraft.Trunk", 35)
    eq(trunk:getInventoryItem():getMaxCapacity(), 120, "still unscaled on respawn")
    Vehicles.applyVehicle(truck, s)
    eq(trunk:getContainerCapacity(), 240, "doubled once")
end)

test("vehicles: occupied seats wait until they are free", function()
    local car, _, _, seat0 = vanillaCar()
    car.seats[0] = "driver"
    local s = settings(100, 200, 100, 100)
    Vehicles.applyVehicle(car, s)
    eq(seat0.container.capacity, 20, "untouched while occupied")
    car.seats[0] = nil
    Vehicles.applyVehicle(car, s)
    eq(seat0:getContainerCapacity(), 40, "scaled once free")
    car.seats[0] = "driver"
    Vehicles.applyVehicle(car, s)
    eq(seat0.container.capacity, 40, "kept while occupied again")
    car.seats[0] = nil
    Vehicles.applyVehicle(car, s)
    eq(seat0:getContainerCapacity(), 40, "not rescaled from the quartered value")
end)

test("vehicles: trailers and campers use the trailer percent; their beds use seats", function()
    Vehicles.resetCaches()
    local bed = Fake.part({ id = "TrailerTrunk", itemTypes = { "Base.TrailerTrunk" }, scriptCapacity = 100 })
    local trailer = Fake.vehicle("Base.Trailer", { bed }, { engine = false })
    Fake.spawnItem(bed, "Base.TrailerTrunk", 0)
    local cabinet = Fake.part({ id = "KI5CRCabsTop", itemTypes = { "damnCraft.Trunk" }, scriptCapacity = 25 })
    local berth = Fake.part({ id = "DAMNBedOne", seat = 2, itemTypes = { "Base.KI5CamperBed0" }, scriptCapacity = 30 })
    local camper = Fake.vehicle("Base.Trailer61Airflyte", { cabinet, berth }, { engine = false })
    Fake.spawnItem(cabinet, "damnCraft.Trunk", 35)
    Fake.spawnItem(berth, "Base.KI5CamperBed0", 0)
    local s = settings(300, 200, 100, 150)
    Vehicles.applyVehicle(trailer, s)
    Vehicles.applyVehicle(camper, s)
    eq(bed:getContainerCapacity(), 150, "trailer bed")
    eq(cabinet:getContainerCapacity(), 38, "camper cabinet")
    eq(berth:getContainerCapacity(), 60, "camper bed counts as a seat")
end)

test("vehicles: changing the percent rescales from the original; 100 restores it", function()
    local car, trunk, glove = vanillaCar()
    Vehicles.applyVehicle(car, settings(200, 100, 300, 100))
    Vehicles.applyVehicle(car, settings(150, 100, 200, 100))
    eq(trunk:getContainerCapacity(), 75, "trunk from 50")
    eq(glove:getContainerCapacity(), 10, "glove box from 5")
    Vehicles.applyVehicle(car, settings(100, 100, 100, 100))
    eq(trunk:getContainerCapacity(), 50, "trunk restored")
    eq(glove:getContainerCapacity(), 5, "glove box restored")
    eq(next(trunk:getModData()), nil, "no mod data left behind")
end)

test("vehicles: a saved and reloaded vehicle stays scaled once", function()
    local car = vanillaCar()
    local s = settings(200, 200, 200, 100)
    Vehicles.applyVehicle(car, s)
    local loaded = Fake.reload(car)
    eq(Vehicles.applyVehicle(loaded, s), 0, "nothing to do after load")
    eq(loaded:getPartById("TruckBed"):getContainerCapacity(), 100, "trunk")
    eq(loaded:getPartById("SeatFrontLeft"):getContainerCapacity(), 40, "seat")
end)

test("vehicles: built-in cargo areas stop at the engine's 1000 limit", function()
    local cargo = Fake.part({ id = "TruckBed", scriptCapacity = 130 })
    local van = Fake.vehicle("Base.Van", { cargo })
    Vehicles.applyVehicle(van, settings(1000, 100, 100, 100))
    eq(cargo:getContainerCapacity(), 1000, "capped")
    Vehicles.applyVehicle(van, settings(1000, 100, 100, 100))
    eq(cargo:getContainerCapacity(), 1000, "stable at the cap")
    Vehicles.applyVehicle(van, settings(100, 100, 100, 100))
    eq(cargo:getContainerCapacity(), 130, "restored")
end)

test("vehicles: parts whose item has no capacity are skipped", function()
    local armor = Fake.part({ id = "DAMNFrontArmor", itemTypes = { "Base.SomeArmor" } })
    local truck = Fake.vehicle("Base.89defender", { armor })
    Fake.spawnItem(armor, "Base.SomeArmor", -1)
    eq(Vehicles.applyVehicle(truck, settings(500, 100, 100, 100)), 0, "nothing changed")
    eq(armor:getContainerCapacity(), 0, "still 0")
end)

test("vehicles: applyLoaded and applyNear reach the right vehicles", function()
    local near = vanillaCar()
    local far = vanillaCar()
    local inside = vanillaCar()
    near.x, near.y = 103, 100
    far.x, far.y = 150, 100
    local game = Fake.install({ near, far, inside })
    local s = settings(200, 100, 100, 100)
    local player = Fake.player(100, 100, inside)
    ok(Vehicles.applyNear(player, s, 6) > 0, "changed some")
    eq(near:getPartById("TruckBed"):getContainerCapacity(), 100, "near")
    eq(inside:getPartById("TruckBed"):getContainerCapacity(), 100, "own vehicle")
    eq(far:getPartById("TruckBed"):getContainerCapacity(), 50, "far untouched")
    local parts, vehicles = Vehicles.applyLoaded(s)
    eq(parts, 1, "only the far trunk was left"); eq(vehicles, 1, "one vehicle")
    eq(far:getPartById("TruckBed"):getContainerCapacity(), 100, "far after sweep")
    ok(game.cell ~= nil, "fake cell")
end)

test("vehicles: report lists each changed part with old and new capacity", function()
    local car = vanillaCar()
    local seen = {}
    Vehicles.applyVehicle(car, settings(300, 100, 200, 100), function(name, changes) seen[#seen + 1] = Vehicles.reportLine(name, changes) end)
    eq(#seen, 1, "one report")
    eq(seen[1], "[VehicleStorageCapacity] Base.CarNormal: TruckBed 50 -> 150, GloveBox 5 -> 10")
    Vehicles.applyVehicle(car, settings(300, 100, 200, 100), function() seen[#seen + 1] = "again" end)
    eq(#seen, 1, "no report when nothing changed")
end)

test("vehicles: no cell (main menu) is a no-op", function()
    local saved = _G.getCell
    _G.getCell = function() return nil end
    local parts, vehicles = Vehicles.applyLoaded(settings(200, 100, 100, 100))
    eq(parts, 0); eq(vehicles, 0)
    _G.getCell = saved
end)
