local Classify = require("VehicleStorageCapacity/classify")

test("classify: trailers by name or missing engine", function()
    ok(Classify.isTrailer("TrailerKI5cargoLarge", false), "KI5 cargo trailer")
    ok(Classify.isTrailer("Trailer61Airflyte", false), "KI5 camper")
    ok(Classify.isTrailer("Base.Trailer", true), "name wins even with an engine")
    ok(Classify.isTrailer("SomeModCart", false), "no engine")
    ok(not Classify.isTrailer("Base.PickUpTruck", true), "pickup")
    ok(not Classify.isTrailer("Base.93fordF350", true), "KI5 truck")
end)

test("classify: seats by seat number or id", function()
    eq(Classify.category({ id = "SeatFrontLeft", seatNumber = 0 }, false), "seat")
    eq(Classify.category({ id = "DAMNBedOne", seatNumber = 4 }, true), "seat", "camper bed")
    eq(Classify.category({ id = "DAMNStretcher", seatNumber = 3 }, false), "seat", "stretcher")
    eq(Classify.category({ id = "SeatRear", seatNumber = -1 }, false), "seat", "id prefix")
end)

test("classify: glove boxes and consoles", function()
    eq(Classify.category({ id = "GloveBox", seatNumber = -1 }, false), "glovebox")
    eq(Classify.category({ id = "DEF89CenterConsole", seatNumber = -1, itemTypes = { "Base.GloveBox" } }, false), "glovebox")
    eq(Classify.category({ id = "Cubby", seatNumber = -1, itemTypes = { "Base.GloveBox" } }, false), "glovebox", "by item")
end)

test("classify: everything else is trunk, or trailer on trailers", function()
    eq(Classify.category({ id = "TruckBed", seatNumber = -1, itemTypes = { "Base.NormalTrunk" } }, false), "trunk")
    eq(Classify.category({ id = "M1031StorageFL", seatNumber = -1, itemTypes = { "damnCraft.Trunk" } }, false), "trunk")
    eq(Classify.category({ id = "VAN63Roofrack", seatNumber = -1 }, false), "trunk", "roof rack")
    eq(Classify.category({ id = "TrailerTrunk", seatNumber = -1 }, true), "trailer")
    eq(Classify.category({ id = "KI5CRCabsTop", seatNumber = -1 }, true), "trailer", "camper cabinet")
end)
